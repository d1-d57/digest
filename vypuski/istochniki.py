#!/usr/bin/env python3
"""Сверка текста с раскладкой: доехало ли до текста то, что обещано на фазе 1.

    python3 istochniki.py <дата>-vypusk-NN

Проверяет три вещи, которые до сих пор держались вниманием:
  · каждое ЧИСЛО и ГОД из выписываемого утверждения раздела есть в тексте этого раздела
    (утверждение, обещанное раскладкой и не доехавшее в текст, — самая дорогая потеря фазы 2);
  · ссылки не дублируются по URL;
  · у каждого раздела число ссылок совпадает с назначенным в раскладке.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import proverki  # noqa: E402
from build_vypusk import split_frontmatter, parse_body  # noqa: E402

BLIND = ['доехало ли САМО утверждение, а не его числа — это верификатор текста',
         'верен ли источник по существу — это гейт 0 разведки, вход фазы 1']

# --- Подводка ссылки: объём и входной порог -----------------------------------
# 🔴 ЭТО ИЗМЕРЕНИЕ, А НЕ ГЕЙТ, И РЕШЕНИЕ ЭТО ОБОСНОВАНО ЗАМЕРОМ, А НЕ ОСТОРОЖНОСТЬЮ.
# `docs/fazy/tekst.md` объявляет условием гейта «подводка каждой ссылки называет
# автора, объём и входной порог». Автора ловит `check_vypusk.py` ([Г5 автор]).
# Объём и порог не ловил никто, и 16.08 это записали как дыру — но перед тем как
# строить рычаг, правило померили по корпусу ПРИНЯТЫХ выпусков:
#
#   выпуск 01 · ссылок 23 · без объёма 17 · без порога 16
#   выпуск 02 · ссылок 15 · без объёма  9 · без порога 10
#   выпуск 03 · ссылок  6 · без объёма  4 · без порога  4
#   выпуск 04 · ссылок 15 · без объёма  2 · без порога  4
#
# То есть правило НЕ ВЫПОЛНЯЕТСЯ на материале, который владелец уже принял, —
# больше чем в половине подводок. Сделать его красным значит покрасить всё
# принятое, а гейт, красный на здоровой работе, отключают целиком вместе со
# всем остальным (тот же разбор — `docs/fazy/stil.md` про снятый механизм).
# Поэтому здесь печатается ЧИСЛО, а красное не ставится: правило либо становится
# решением владельца «впредь так, старые выпуски — исключение», либо перестаёт
# называться условием гейта в файле фазы. Третьего — «условие есть, носителя нет,
# и об этом молчат» — не бывает: это и есть халтура по определению протокола.
CHISLA = (r'(?:\d+|одн[аои]|дв[аеух]|тр[иёе]х?|четыр[еёх]|пят[ьи]|шест[ьи]|сем[ьи]|'
          r'восем[ьи]|девят[ьи]|десят[ьи]|одиннадцат|двенадцат|тринадцат|четырнадцат|'
          r'пятнадцат|шестнадцат|семнадцат|восемнадцат|девятнадцат|двадцат|тридцат|'
          r'сорок|пятьдесят|сто|двести|полтор|несколько|десятк|сотн)')
EDINICY = r'(?:страниц|полос|экран|минут|час[ао]|слайд|разворот|том)'
OBYOM = re.compile(CHISLA + r'\w*\s+(?:\w+\s+){0,2}' + EDINICY, re.I)
POROG = re.compile(r'требует|нужен|нужн[оа]|без формул|формул почти нет|знать заранее|'
                   r'для студент|для математик|неспециалист|предварительн|вход|школьн|'
                   r'с нуля|популярн|обзор|доступн', re.I)


def main(name):
    d = Path(__file__).parent / name
    rask = (d / 'RASKLADKA.md').read_text(encoding='utf-8')
    _meta, body = split_frontmatter((d / 'vypusk.md').read_text(encoding='utf-8'))
    _lead, rubrics = parse_body(body)
    items = [it for _rn, its in rubrics for it in its]

    rows = {}
    for l in rask.split('\n'):
        m = re.match(r'^\|\s*(\d+)\s*\|', l)
        if m:
            c = [x.strip() for x in l.strip('|').split('|')]
            rows[int(m.group(1))] = c

    errs, urls = [], {}
    for i, it in enumerate(items, 1):
        c = rows.get(i)
        if not c:
            errs.append(f'раздел {i}: нет строки в раскладке')
            continue
        utv, ssy = c[3], c[5]
        tekst = it['blurb'].replace('{,}', ',').replace('{.}', '.')
        # числа утверждения: годы и величины, кроме одиночных цифр-порядков
        nums = [n for n in re.findall(r'\d[\d  ,.]*\d|\d', utv) if len(n) > 1]
        poteryano = [n for n in nums if n.replace(' ', '') not in tekst.replace(' ', '')]
        if poteryano:
            errs.append(f'раздел {i}: числа из выписываемого утверждения не найдены в тексте — '
                        f'{", ".join(poteryano)}')
        want = int(re.findall(r'\d+', ssy)[0])
        got = len(it['meta'].get('links') or [])
        if want != got:
            errs.append(f'раздел {i}: ссылок {got}, раскладка назначала {want}')
        for ln in (it['meta'].get('links') or []):
            urls.setdefault(ln['url'], []).append(i)

    for u, gde in urls.items():
        if len(gde) > 1:
            errs.append(f'ссылка повторяется в разделах {gde}: {u}')

    # Подводки: печатаем ЧИСЛО, красное не ставим — обоснование у объявления OBYOM.
    vse_ssylki = [(i, ln) for i, it in enumerate(items, 1)
                  for ln in (it['meta'].get('links') or [])]
    bez_ob = [i for i, ln in vse_ssylki if not OBYOM.search(ln['about'])]
    bez_por = [i for i, ln in vse_ssylki if not POROG.search(ln['about'])]
    print(f'ПОДВОДКИ · ссылок {len(vse_ssylki)} · без объёма {len(bez_ob)} '
          f'(разделы {sorted(set(bez_ob)) or "—"}) · без входного порога {len(bez_por)} '
          f'(разделы {sorted(set(bez_por)) or "—"})')
    print('   ⚠ измерение, не гейт: правило «подводка называет объём и входной порог» '
          'не выполняется\n     и на ПРИНЯТЫХ выпусках (02: 9 из 15 без объёма, 03: 4 из 6). '
          'Красить им нельзя,\n     пока владелец не решит «впредь так» — либо пока условие '
          'не уберут из docs/fazy/tekst.md.\n')

    print('НЕ проверяю:')
    for b in BLIND:
        print(f'   · {b}')
    print()
    for e in errs:
        print('✗ ' + e)
    if errs:
        print(f'\n✗ сверка с раскладкой красная: {len(errs)}')
        return 1
    print('✓ сверка с раскладкой сошлась: числа утверждений доехали, ссылки без дублей\n')
    proverki.avtomark(d, 'istochniki',
                      'числа выписываемых утверждений найдены в своих разделах, ссылки без дублей, '
                      'число ссылок совпадает с раскладкой')
    return proverki.gate(d, 'tekst')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))

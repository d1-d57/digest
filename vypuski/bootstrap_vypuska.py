#!/usr/bin/env python3
"""Заводит папку выпуска: анкета раскладки, отчёт о проверках, каркас текста.

    python3 bootstrap_vypuska.py 2026-08-15-vypusk-04 [--razdelov 6]

Структуру руками не заводят. Всё незаполненное несёт слово «заполнить» и краснеет
на гейте: проблема не в том, что исполнитель врёт про проделанную работу, а в том,
что он забывает под длинной инструкцией (PROTOKOL-VYPUSKA.md, Н5).
"""
import sys
from pathlib import Path

RASKLADKA = """# Раскладка выпуска {name}

Фаза 1 протокола (`docs/PROTOKOL-VYPUSKA.md`). Текста здесь нет — только структура.
Гейт: `python3 vypuski/check_raskladka.py {name}`

rezhim: заполнить            # хроника | лестница (К6)
formula_v_razdele: заполнить  # номер раздела с единственной выключной формулой
potolok_prozy: 10000          # К5

## Лид — четыре шага К1, новость последней

1. задача: заполнить
2. что известно и что неизвестно: заполнить
3. как устроено известное: заполнить
4. новость с датой: заполнить

## Разделы

| # | имя | вокруг чего | выписываемое утверждение | byudzhet | ssylki |
|---|---|---|---|---|---|
{rows}
## Не входит

- заполнить

## Порядок сокращения

1. заполнить

<!-- строка приёмки: ПРИНЯТО фаза-1: <дата> -->
"""

OTCHET = """# Отчёт о проверках — выпуск {name}

Заполняется РУКАМИ перед предъявлением владельцу. След обязателен: не галочка, а что
искал, что нашёл, что исправил. Пустой след равен непроведённой проверке.
Незаполненная строка красит `check_vypusk.py` независимо от текста.

| проверка | след |
|---|---|
| math-russian-terminology по всем терминам и именам | заполнить |
| russian-editor по всему тексту целиком | заполнить |
| канон К1: лид от общего к частному, новость последней | заполнить |
| канон К5: бюджеты разделов из раскладки выдержаны | заполнить |
| верификатор-субагент со свежим контекстом, вердикт | заполнить |
| гейт 0 разведки: какие пункты закрыты при письме | заполнить |
"""


def main(name, n):
    d = Path(__file__).parent / name
    d.mkdir(exist_ok=True)
    rows = ''.join(f'| {i} | заполнить | заполнить | заполнить | заполнить | заполнить |\n'
                   for i in range(1, n + 1))
    for fn, tpl in (('RASKLADKA.md', RASKLADKA), ('OTCHET.md', OTCHET)):
        f = d / fn
        if f.exists():
            print(f'· {fn} уже есть, не трогаю')
            continue
        f.write_text(tpl.format(name=name, rows=rows), encoding='utf-8')
        print(f'✓ {f}')
    return 0


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    k = sys.argv.index('--razdelov') if '--razdelov' in sys.argv else -1
    sys.exit(main(sys.argv[1], int(sys.argv[k + 1]) if k > 0 else 6))

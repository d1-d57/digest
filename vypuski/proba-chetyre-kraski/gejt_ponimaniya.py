#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПРОТОТИП РЫЧАГА к пункту расписки фазы `karta`, у которого носителя нет:

    «блок, содержания не дающий, помечен `otsylka`, а не строгим статусом»

Заказ владельца 12.09.2026, дословно: «в основе изложения таких вещей, которые
непонятны — то есть ты сказал математическое утверждение, но не понятен его
смысл — таких не должно быть. И мы пытаемся выстроить структуру так, чтобы такие
утверждения ловить и запрещать».

# TOOL-CONTRACT: called-by-hand, прототип в папке пробного выпуска.
# Живёт ЗДЕСЬ, а не в `vypuski/`, потому что вводит НОВОЕ ПОЛЕ ШАПКИ, а поля
# шапки зашиты регуляркой в `build_vypusk.py:bloki` (строка 339): движок читает
# ровно `зачем|мысль|опирается|объём` и новое поле не увидит. Переезд в
# дисциплину = правка этой регулярки + условие в `docs/fazy/karta.md` + вызов из
# `check_bloki.py`, то есть отдельный заход с коммитом в производственный дом.

ЧТО ВВОДИТ. Пятое поле шапки блока:

    понимание: <что читатель сможет сделать сам, прочитав блок>

ЧТО КРАСНЕЕТ (три условия, все машинные):

  П1 · у блока строгого рода поле `понимание` есть и непусто.
       Строгие рода берутся из `check_bloki.STROGIE`, второго дома списка нет.

  П2 · `понимание` сформулировано как проверяемое умение, а не как пересказ
       мысли: содержит глагол читательского действия из закрытого списка ниже.
       «Читатель поймёт важность метода» — не умение, проверить нечего.
       «Читатель проверит равенство сам» — умение, у него есть исход.

  П3 · у блока вольного рода поле `понимание` ЗАПРЕЩЕНО. Если его удалось
       написать, блок несёт содержание и обязан быть строгим; если оставить
       вольным — содержание уйдёт в текст необъявленным. Это обратная
       болезнь, и замер фазы `karta` показывает, что она живая: восемь
       невосстановимых блоков выпуска 04 помечены строгими при нуле отсылок.

ЧЕГО ЭТОТ ГЕЙТ НЕ ПРОВЕРЯЕТ — печатается всегда:
  · формируется ли заявленное понимание НА САМОМ ДЕЛЕ. Это верификатор
    понятности по блоку (`docs/verifikatory/ponyatnost.md`), и поле `понимание`
    даёт ему то, чего у него до сих пор не было: вопрос «возникло ли ИМЕННО
    ЭТО понимание» вместо вопроса «понятно ли вообще».
  · достаточно ли одного блока, чтобы умение возникло: это суждение.

    python3 gejt_ponimaniya.py <файл vypusk.md>
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from check_bloki import STATUSY, STROGIE  # noqa: E402  — один дом списка родов

# Глаголы читательского действия. Закрытый список: у каждого есть проверяемый
# исход, который может предъявить верификатор. «Поймёт», «оценит», «осознает»
# сюда НЕ входят — у них исхода нет, и ими закрывают дыру, а не объясняют.
DEJSTVIYA = (
    "проверит", "пересчитает", "посчитает", "выведет", "восстановит",
    "сформулирует", "назовёт", "приведёт", "отличит", "применит",
    "построит", "предъявит", "объяснит", "сверит", "укажет",
)
SHAPKA_RE = re.compile(r"^%%\s*([\w.]+)\s*·\s*(\w+)\s*$", re.M)


def bloki_s_ponimaniem(src: str):
    """[(id, род, {поля})]. Разбор локальный: движок пятое поле не читает."""
    out = []
    for kus in re.split(r"^%%\s", src, flags=re.M)[1:]:
        golova = kus.split("\n\n", 1)[0]
        m = re.match(r"([\w.]+)\s*·\s*(\w+)", golova)
        if not m:
            continue
        polya = dict(re.findall(r"^(зачем|мысль|опирается|объём|понимание):\s*(.+)$",
                                golova, re.M))
        out.append((m.group(1), m.group(2), polya))
    return out


def proverit(put: pathlib.Path):
    src = put.read_text(encoding="utf-8")
    bedy, vsego, s_polem = [], 0, 0

    for bid, rod, polya in bloki_s_ponimaniem(src):
        if rod not in STATUSY:
            continue                      # чужие рода судит check_bloki.py
        vsego += 1
        pon = (polya.get("понимание") or "").strip()
        strogij = rod in STROGIE

        if strogij and (not pon or pon == "заполнить"):
            bedy.append(("П1", bid, rod,
                         "строгий блок без поля «понимание»: сказать утверждение "
                         "и не назвать, что из него должен понять читатель, — "
                         "ровно то, что запрещено"))
        elif strogij:
            s_polem += 1
            if not any(g in pon.lower() for g in DEJSTVIYA):
                bedy.append(("П2", bid, rod,
                             "«понимание» без глагола читательского действия — это "
                             "пересказ мысли, а не умение; проверить его нечем. "
                             "Разрешены: " + ", ".join(DEJSTVIYA[:6]) + " и др."))
        elif pon and pon != "заполнить":
            bedy.append(("П3", bid, rod,
                         "у вольного блока заполнено «понимание»: если умение "
                         "формулируется, блок несёт содержание и обязан быть "
                         "строгим — иначе содержание уйдёт в текст необъявленным"))

    print("── ГЕЙТ ПОНИМАНИЯ (прототип, фаза karta) ──")
    print(f"  {put}")
    print(f"  блоков разобрано: {vsego} · строгих с заполненным «понимание»: {s_polem}")
    print("\n  ЧЕГО ЭТОТ ГЕЙТ НЕ ПРОВЕРЯЕТ — список закрытый:")
    print("     · формируется ли заявленное понимание на самом деле — верификатор понятности")
    print("     · достаточно ли одного блока, чтобы умение возникло — суждение")

    if bedy:
        print(f"\n  ✗ КРАСНЫЙ — замечаний {len(bedy)}:")
        for kod, bid, rod, chto in bedy:
            print(f"     {kod}  блок {bid} [{rod}]: {chto}")
        return 1
    print("\n  ✓ ЗЕЛЁНЫЙ: у каждого строгого блока объявлено проверяемое умение, "
          "вольные блоки содержания не несут")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("python3 gejt_ponimaniya.py <файл vypusk.md>")
    sys.exit(proverit(pathlib.Path(sys.argv[1])))

#!/usr/bin/env python3
"""Дерево опор выпуска: кто на кого опирается и какой строгости требует блок.

    python3 opory.py <папка выпуска>

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Поле `опирается` в шапке блока заполняли, а читать его
было некому: `docs/fazy/karta.md` объявляет условием гейта «граф опор непуст» с
маркером `[У4]`, но в `check_bloki.py` проверки нет — слово «опирается» встречается
там один раз, в проверке непустоты поля, а прочерк поле не опустошает. Цена, замер
16.08.2026: у ВСЕХ 23 блоков выпуска 04 стояло `опирается: —`, гейт блоков был
зелёный, и `zamer_korpusa.py` показывал 0,00 опор на блок при 1,23 в выпуске 02.
Правило было объявлено с носителем, носителя не было.

ВТОРАЯ ЦЕНА, ДОРОЖЕ ПЕРВОЙ. Когда дерево заполнили, им всё равно не воспользовались:
исполнитель дописал полные определения ВЕЗДЕ, где верификатор понятности сказал
«непонятно», — в том числе в блоках, на которые дальше не опирается ничто. Выпуск
вырос с 11 881 знака до 18 982, то есть на 60 %, и вышел за корпус в полтора раза.
Владелец 16.08: «если на рядах Эйзенштейна ничего не висит, то зачем туда писать
полное определение? Мы же пишем дайджест, а не переписываем Википедию».

Отсюда назначение этого файла — не только покраснеть на пустом графе, но и СКАЗАТЬ,
какой строгости требует каждый блок. Строгость выводится из графа, а не из вкуса:

  · ОПОРНЫЙ  — на блок опирается хотя бы один другой. Понятие, введённое здесь,
               работает дальше по тексту, и объяснять его надо полностью.
  · ЛИСТ     — на блок не опирается никто. Термин можно назвать именем и отправить
               ссылкой (роль `отсылка` в PONYATIYA.md). Полное определение здесь —
               не строгость, а лишние знаки: они уходят в объём и ни на что не
               работают.
  · НАРРАТИВ — статус `narrativ`. Блок рассказывает, а не утверждает; вопрос
               «восстанавливается ли утверждение» ему не задаётся вовсе.

⚠ ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ. Он не судит, ВЕРНО ли проставлены опоры: блок можно
объявить опирающимся на что угодно. Разрывы («опирается на блок, который нужного не
даёт») ловит верификатор карты, и это его работа, а не регулярки.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import proverki                                             # noqa: E402

STROGIE = {'utverzhdenie', 'opredelenie', 'vyvod', 'ogovorka'}


def razobrat(text):
    """[(блок, статус, [опоры])] в порядке появления."""
    bloki, tek = [], None
    for l in text.split('\n'):
        m = re.match(r'^%%\s+(\S+)\s+·\s+(\S+)\s*$', l)
        if m:
            tek = {'id': m.group(1), 'status': m.group(2), 'opory': []}
            bloki.append(tek)
        elif tek is not None and l.startswith('опирается:'):
            hvost = l.split(':', 1)[1].strip()
            if hvost and hvost != '—':
                tek['opory'] = [x.strip() for x in hvost.split('·') if x.strip()]
    return bloki


def main(papka):
    d = Path(papka)
    d = d if d.is_dir() else d.parent
    f = d / 'vypusk.md'
    if not f.exists():
        print(f'✗ нет {f}')
        return 1
    bloki = razobrat(f.read_text(encoding='utf-8'))
    if not bloki:
        print('✗ блочной разметки `%%` нет — выпуск старше протокола, дерева опор у него нет')
        return 1

    est = {b['id'] for b in bloki}
    vhod = {b['id']: 0 for b in bloki}
    bedy, warns = [], []

    for b in bloki:
        for o in b['opory']:
            if o not in est:
                bedy.append(f'{b["id"]}: опирается на несуществующий блок «{o}»')
            else:
                vhod[o] += 1

    vsego_opor = sum(len(b['opory']) for b in bloki)
    print(f'Блоков: {len(bloki)} · рёбер: {vsego_opor} · опор на блок: '
          f'{vsego_opor / len(bloki):.2f}  (корпус: 1,23 в выпуске 02 · 1,00 в 03)\n')

    print(f'{"блок":>6}  {"статус":<13}{"на него":>8}  строгость понятности')
    for b in bloki:
        n = vhod[b['id']]
        if b['status'] == 'narrativ':
            rezhim = 'НАРРАТИВ · вопрос про утверждение не задаётся'
        elif n:
            rezhim = f'ОПОРНЫЙ · объяснять полностью, дальше опирается {n}'
        else:
            rezhim = 'ЛИСТ · термин можно назвать и отдать ссылкой'
        print(f'{b["id"]:>6}  {b["status"]:<13}{n:>8}  {rezhim}')
    print()

    # 🔴 Носитель условия 3 фазы `karta`. Узкое условие выбрано намеренно, как и
    # написано в файле фазы: «правильная» доля опор есть суждение, а пустой граф —
    # факт. Красное только на полностью пустом графе.
    if vsego_opor == 0:
        bedy.append('граф опор ПУСТ: ни один блок не опирается ни на один. Поле '
                    '`опирается` заполнено прочерками, то есть механизм описан и не '
                    'наполнен (docs/fazy/karta.md, условие 3 гейта)')

    # Лид опирать не на что — он первый; предупреждаем только про разделы.
    siroty = [b['id'] for b in bloki
              if not b['opory'] and not b['id'].startswith('Л') and b['status'] in STROGIE]
    if siroty:
        warns.append('строгие блоки без единой опоры: ' + ' · '.join(siroty) +
                     ' — проверь, правда ли они ни на чём не стоят')

    opornyh = sum(1 for b in bloki if vhod[b['id']] and b['status'] != 'narrativ')
    listyev = sum(1 for b in bloki if not vhod[b['id']] and b['status'] != 'narrativ')
    print(f'ИТОГО: опорных {opornyh} · листьев {listyev} · нарративных '
          f'{sum(1 for b in bloki if b["status"] == "narrativ")}')
    print('   Понятность спрашивается СТРОГО с опорных; с листьев — по мере того, что '
          'на них висит;\n   нарративные из вопроса про утверждение исключены. '
          'Полное определение в листе — лишние знаки.\n')

    for w in warns:
        print('⚠ ' + w)
    for b in bedy:
        print('✗ ' + b)
    if bedy:
        print(f'\n✗ гейт опор красный: {len(bedy)}')
        return 1
    print(f'✓ гейт опор зелёный ({len(warns)} подозрений)')
    return 0


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))

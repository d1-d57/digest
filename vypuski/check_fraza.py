#!/usr/bin/env python3
"""Фраза без утверждения — два класса, оба выведены из вердиктов владельца 2026-08-17.

    python3 check_fraza.py <папка выпуска|файл.md> [--vse]

🔴 ЧЕМ ЭТОТ ГЕЙТ ОТЛИЧАЕТСЯ ОТ `check_idioma.py`. Тот ловит НЕЗАКОННЫЙ ОБОРОТ: слова стоят вместе
так, как по-русски математики не говорят. Этот ловит ФРАЗУ, КОТОРАЯ НИЧЕГО НЕ УТВЕРЖДАЕТ: оборот в
ней может быть безупречен. Владелец сформулировал предмет одной строкой: *«текст должен содержать
смысл»*. Два класса — разные, и мешать их нельзя: незаконный оборот правят заменой слова, пустую
фразу правят вычёркиванием или возвратом подлежащего.

ОТКУДА КЛАССЫ. Владелец 17.08 назвал три места в выпуске 4, аналитик обобщил их в два класса и
прогнал по всему тексту; из шести новых находок владелец подтвердил шесть.

  A · ФРАЗА О СТРУКТУРЕ ТЕКСТА, А НЕ О МАТЕМАТИКЕ.
      «Дальше по годам.» · «К этим результатам мы ещё вернёмся.» · «поэтому дальше речь о том, что
      происходит с оценками при росте размерности». Такая фраза сообщает читателю, как устроено
      изложение, вместо того чтобы сообщить факт. Правится вычёркиванием.

  B · ОБРУБЛЕННОЕ НАЧАЛО: личный глагол первым словом, подлежащее позади или отсутствует.
      «Понадобятся многочлены Гегенбауэра» → «Нам понадобятся…» · «Выписали его Кон и Элкис» →
      «Его выписали…» · «Требует функционального анализа» — подлежащее выброшено совсем.

🔴 ЧТО ГЕЙТ НЕ КРАСНИТ, И ЭТО ЗАМЕРЕНО, А НЕ ПРИДУМАНО. Первое лицо множественного числа
(«Расставим шары», «Перейдём к оценке») — наш регистр, а не обрубок; оно снимается по морфологии.
Смысловая инверсия с вынесенным вперёд дополнением («Плотнейшую упаковку нашла Вязовская») в класс B
не попадает: первым словом там не глагол. Заголовки не судятся вовсе — заголовок не фраза.

⚠ ГЕЙТ НЕ ВЫНОСИТ ВЕРДИКТОВ. Как и `check_idioma.py`, он показывает места, а решает человек. Класс A
опирается на список зачинов и потому неполон; класс B на пограничных случаях спорен.

🔴 КОНТРОЛЬ НА ПРИНЯТОМ МАТЕРИАЛЕ — обязательная часть этого гейта, а не приложение к нему.
Правило, выведенное из одного текста, бракует то, что владелец уже принял. Поэтому класс B прогнан
по выпускам 02 и 03, принятым владельцем. Первая редакция дала на них 6 срабатываний; после
снятия безличных («Оказалось, что…», «Стоит заметить…») осталось 4:

    выпуск 02 · «Штурмовали по двум осям…» · «Читается легче обзоров» (описание ссылки)
    выпуск 03 · «Работают оба свойства одинаково.» · «Держится конструкция на критерии…»

**Эти четыре фразы владелец принял.** Значит, класс B ловит ФОРМУ, внутри которой есть и брак, и
норма, и вердикта он не выносит по устройству. Отдельно стоит отметить: «Читается легче обзоров» —
ровно та же форма, что забракованное 17.08 «Требует функционального анализа» (в обоих подлежащее
выброшено в описании ссылки). Пока владелец не разберёт эту пару, порог класса B считается
неоткалиброванным. [ДОЛГ: docs/DOLGI.md#Д27]

Цена срабатываний: около двух мест на выпуск — их дешевле просмотреть глазами, чем пропустить.

Требует spaCy: pip install spacy --break-system-packages && модель ru_core_news_sm

🔴 ПОЛОСА А · ЯДРО — файл уедет в скилл финальной правки вместе с `check_idioma.py`.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from check_idioma import chistka  # noqa: E402

# Зачины и обороты, которыми фраза говорит про порядок изложения, а не про предмет.
# Список выведен из вердиктов владельца по выпуску 4 и неполон — пополняется вердиктами.
STRUKTURA = re.compile(
    r'(дальше по годам|дальше речь|речь дальше|мы ещё вернёмся|вернёмся к этому|'
    r'об этом ниже|об этом выше|см\.\s|по ссылке|подробнее в|как сказано выше|'
    r'ниже по тексту|выше по тексту|в этом разделе речь|перейдём к рассказу)', re.I)

# Безличные: подлежащего у них не бывает по устройству, а не по недосмотру автора.
BEZLICHNYE = {'оказаться', 'оказываться', 'стоить', 'следовать', 'хватать', 'хватить',
              'требоваться', 'приходиться', 'прийтись', 'удаваться', 'удаться', 'случиться',
              'получаться', 'получиться', 'выходить', 'выйти', 'бывать'}


def proza_bez_zagolovkov(syroj):
    """Публикуемая проза БЕЗ заголовков. Заголовок — не фраза, судить его этими классами нельзя."""
    lines = syroj.split('\n')
    i = 0
    if lines and lines[0].strip() == '---':
        i = lines.index('---', 1) + 1
    out, opisaniya, v_shapke = [], [], False
    for ln in lines[i:]:
        s = ln.strip()
        if s.startswith('%%'):
            v_shapke = True
            continue
        if s.startswith('===='):
            v_shapke = False
            continue
        if v_shapke or s.startswith('|') or s.startswith('#') or re.match(r'-\s*areas:', s):
            continue
        m = re.match(r'-\s*link:\s*(.+)', s)
        if m:
            ch = [c.strip() for c in m.group(1).split('|')]
            if len(ch) >= 3:
                opisaniya.append(ch[-1])
            continue
        out.append(ln)
    return chistka('\n'.join(out)), chistka('\n'.join(opisaniya))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('put')
    ap.add_argument('--vse', action='store_true', help='печатать и пограничные случаи класса B')
    a = ap.parse_args()

    p = Path(a.put)
    fajl = p / 'vypusk.md' if p.is_dir() else p
    if not fajl.exists():
        print(f'✗ нет файла {fajl}')
        return 1
    try:
        import spacy
        import pymorphy3
        nlp = spacy.load('ru_core_news_sm', disable=['ner', 'parser'])
        if 'sentencizer' not in nlp.pipe_names:
            nlp.add_pipe('sentencizer')
        morph = pymorphy3.MorphAnalyzer()
    except Exception as e:
        print(f'✗ нужны spaCy с моделью ru_core_news_sm и pymorphy3: {e}')
        return 1

    tekst, opisaniya = proza_bez_zagolovkov(fajl.read_text(encoding='utf-8'))
    A, B = [], []
    for istochnik, imya in ((tekst, 'проза'), (opisaniya, 'описание ссылки')):
        for kus in [istochnik[i:i + 40000] for i in range(0, len(istochnik), 40000)]:
            for sent in nlp(kus).sents:
                txt = sent.text.strip()
                if len(txt) < 8:
                    continue
                if STRUKTURA.search(txt):
                    A.append((imya, txt))
                toks = [t for t in sent if t.is_alpha]
                if not toks or toks[0].pos_ != 'VERB':
                    continue
                if 'Fin' not in str(toks[0].morph.get('VerbForm')):
                    continue
                # 🔴 «Значит, …» spaCy размечает как глагол; в этом жанре в начале фразы это
                # всегда связка, а не сказуемое. Снимается по лемме, а не по разбору.
                if toks[0].lemma_.lower() == 'значить':
                    continue
                # 🔴 БЕЗЛИЧНЫЕ — подлежащего у них не бывает, обрубком они не являются.
                # Список выведен КОНТРОЛЕМ на принятых выпусках 02 и 03, а не из головы: там
                # «Оказалось, что…» и «Стоит заметить…» владелец принял.
                if toks[0].lemma_.lower() in BEZLICHNYE:
                    continue
                # 🔴 Первое лицо множественного («Расставим», «Перейдём») — наш регистр, не обрубок.
                # spaCy здесь врёт: «Перейдём» она метит Person=Third. Лицо берётся у pymorphy3.
                razbor = [x for x in morph.parse(toks[0].text) if 'VERB' in x.tag]
                if any(str(x.tag.person) == '1per' and str(x.tag.number) == 'plur'
                       for x in razbor):
                    continue
                B.append((imya, txt))

    print(f'ФАЙЛ: {fajl}')
    print(f'A · ФРАЗА О СТРУКТУРЕ ТЕКСТА, А НЕ О МАТЕМАТИКЕ — {len(A)}')
    for imya, t in A:
        print(f'  [{imya}] {t[:150]}')
    if not A:
        print('  нет')
    print(f'\nB · ОБРУБЛЕННОЕ НАЧАЛО: глагол первым словом, подлежащее позади или отсутствует — '
          f'{len(B)}')
    for imya, t in B:
        print(f'  [{imya}] {t[:150]}')
    if not B:
        print('  нет')
    print('\n⚠ Гейт показывает места, а не выносит вердикты. Класс A неполон (список зачинов), '
          'класс B на пограничных случаях спорен — решает человек.')
    return 0


if __name__ == '__main__':
    sys.exit(main())

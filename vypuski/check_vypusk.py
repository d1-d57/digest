# вреднее отсутствующей проверки: он создаёт уверенность, что объём проверен.

SKIP_PREFIX = ('- link', '- areas', '#', '%%', 'зачем:', 'мысль:',
               'опирается:', 'объём:', '====', '|')


def vidimaya_proza(body):
    """Знаки прозы, которые видит читатель, по разделам.

    Считается ровно то, что доезжает до страницы: без шапок блоков, маркеров,
    подводок ссылок, заголовков и areas. Мерить надо этим, а не длиной файла:
    у выпуска 4 разница между «телом» и видимой прозой — 12 тысяч знаков,
    и меряя тело, потолок можно не заметить вовсе.
    """
    razdely = {}
    for kus in re.split(r'\n# ', '\n' + body):
        zagolovok = kus.split('\n')[0].strip()
        nomer = (re.match(r'(\d+)', zagolovok) or [None, 'лид'])[1]
        stroki = [l for l in kus.split('\n')
                  if l.strip() and not l.startswith(SKIP_PREFIX)]
        if stroki:
            razdely[nomer] = razdely.get(nomer, 0) + len('\n'.join(stroki))
    return razdely


# 🔴 Допуск к корпусной норме. Разброс между выпусками настоящий — 1514 знаков на
# раздел в выпуске 02 против 2090 в 03, — и норма, требующая попасть в точку,
# краснела бы на здоровой работе. Двадцать процентов взяты решением владельца
# 16.08 («на 15 %, например, 20 %») и подлежат пересчёту, когда корпус вырастет:
# на двух выпусках дисперсию не оценивают, её оценивают на пяти.
DOPUSK = 0.20
KORPUS_MIN = 2          # меньше двух выпусков — нормы нет, и это говорится вслух


def korpusnaya_norma(papka):
    """Норма объёма, посчитанная ПО КОРПУСУ принятых выпусков, а не вписанная руками.

    Возвращает (норма_знаков, таблица, беда). Норма — это
    `среднее на раздел × число разделов этого выпуска + среднее лида`.

    Почему на раздел, а лид отдельно: лид по К1 — три абзаца независимо от того,
    сколько в выпуске разделов, и амортизировать его по разделам значит завышать
    норму тем выпускам, у которых разделов больше. Выпуск 4 с семью разделами
    получил бы прибавку просто за то, что он длиннее.

    🔴 Старые выпуски при этом НЕ редактируются: они читаются как есть, и
    формула сама пересчитывается, когда корпус растёт. Выпуски без разделов
    (`# N · Имя`) в корпус не идут — это другой формат, а не маленький выпуск.
    """
    tek = papka.resolve()
    tabl, na_razdel, lidy = [], [], []
    for f in sorted(papka.parent.glob('*/vypusk.md')):
        if f.parent.resolve() == tek:
            continue
        try:
            _, b = split_frontmatter(f.read_text(encoding='utf-8'))
        except Exception:
            continue
        d = vidimaya_proza(b)
        lid = d.pop('лид', 0)
        if len(d) < 2:
            continue
        per = sum(d.values()) / len(d)
        tabl.append((f.parent.name, lid, sum(d.values()), len(d), per))
        na_razdel.append(per)
        lidy.append(lid)
    if len(na_razdel) < KORPUS_MIN:
        return None, tabl, (f'в корпусе {len(na_razdel)} выпуск(ов) с разделами, '
                            f'нужно хотя бы {KORPUS_MIN} — норма не считается')
    _, b = split_frontmatter(Path(tek / 'vypusk.md').read_text(encoding='utf-8'))
    n_tek = len([k for k in vidimaya_proza(b) if k != 'лид'])
    sr = sum(na_razdel) / len(na_razdel)
    sr_lid = sum(lidy) / len(lidy)
    return round(sr * n_tek + sr_lid), tabl, None


def byudzhety_raskladki(papka):
    """(потолок, {номер раздела: бюджет}) из RASKLADKA.md, либо (None, {}, причина)."""
    f = papka / 'RASKLADKA.md'
    if not f.exists():
        return None, {}, f'RASKLADKA.md не найдена в {papka}'
    t = f.read_text(encoding='utf-8')
    m = re.search(r'^potolok_prozy:\s*(\d+)', t, re.M)
    potolok = int(m.group(1)) if m else None
    byudzh = {}
    for stroka in t.split('\n'):
        if not stroka.startswith('|'):
            continue
        cells = [c.strip() for c in stroka.strip('|').split('|')]
        if len(cells) < 3 or not cells[0].isdigit():
            continue
        # бюджет — предпоследняя числовая колонка (последняя — число ссылок)
        chisla = [c for c in cells[1:] if c.isdigit()]
        if len(chisla) >= 2:
            byudzh[cells[0]] = int(chisla[-2])
    if potolok is None:
        return None, byudzh, 'в RASKLADKA.md нет строки `potolok_prozy:`'
    if not byudzh:
        return potolok, {}, 'в RASKLADKA.md не разобрана таблица бюджетов разделов'
    return potolok, byudzh, None


def gejt_obyoma(papka, body, errs, warns):
    # 🔴 Развилка «неприменимо» против «пропущено» — и она НЕ по наличию файла.
    # Раскладка и блочная разметка `%%` введены одним и тем же протоколом (v2.0),
    # раньше их не было ни у кого: выпуски 01–03 приняты без RASKLADKA.md.
    # Краснеть на них нельзя — гейт, красный на здоровой работе, отключают целиком
    # вместе со всем остальным (docs/fazy/stil.md, разбор снятого механизма).
    # Но и «нет файла → молча пропускаем» нельзя: это лазейка, которой гейт
    # выключается удалением. Признаком берём МАРКЕРЫ БЛОКОВ: они от того же
    # протокола, и на них стоят фазы karta, ponyatnost и stil. Снести разметку,
    # чтобы обойти проверку объёма, значит обрушить три других гейта разом.
    po_novomu = re.search(r'^%%\s', body, re.M) is not None
    potolok, byudzh, beda = byudzhety_raskladki(papka)

    if beda and potolok is None:
        if not po_novomu:
            print('К5 · объём: НЕПРИМЕНИМО — выпуск без блочной разметки `%%`, '
                  'то есть старше протокола с раскладкой. Проверять не с чем, '
                  'и это не пропуск.\n')
            return
        errs.append(f'[К5 объём] проверка объёма НЕ ПРОВЕДЕНА: {beda}. Это красное, '
                    f'а не пропуск: у выпуска есть блочная разметка, значит он '
                    f'ведётся по протоколу с раскладкой, и потолок обязан быть')
        return
    if beda:
        warns.append(f'[К5 объём] {beda} — бюджеты разделов не проверены')

    fakt = vidimaya_proza(body)
    vsego = sum(fakt.values())

    # --- корпусная норма: потолок раскладки сам обязан быть в её пределах -----
    norma, tabl, net_normy = korpusnaya_norma(papka)
    if tabl:
        print('К5 · корпус принятых выпусков (старые не редактируются, читаются как есть):')
        print(f'   {"выпуск":26}{"лид":>7}{"разделы":>9}{"n":>4}{"на раздел":>11}')
        for imya, lid, raz, n, per in tabl:
            print(f'   {imya:26}{lid:>7}{raz:>9}{n:>4}{per:>11.0f}')
    if net_normy:
        warns.append(f'[К5 норма] {net_normy} — проверен только потолок раскладки')
        print()
    else:
        predel = round(norma * (1 + DOPUSK))
        print(f'   норма по корпусу: {norma} знаков · допуск +{DOPUSK:.0%} → предел {predel}\n')
        if potolok > predel:
            errs.append(f'[К5 норма] потолок раскладки {potolok} выше корпусной нормы '
                        f'{norma} с допуском (+{DOPUSK:.0%} → {predel}). Потолок назначается '
                        f'не свободно: он обязан держаться корпуса, иначе выпуск растёт '
                        f'тем, что сам себе разрешает расти')
        if vsego > predel:
            errs.append(f'[К5 норма] проза {vsego} знаков при корпусной норме {norma} '
                        f'(+{100 * vsego / norma - 100:.0f} %, предел с допуском {predel}) — '
                        f'выпуск вышел за корпус, а не за собственный потолок')

    print(f'К5 · объём видимой прозы: {vsego} знаков при потолке {potolok} '
          f'({100 * vsego / potolok - 100:+.0f} %)')
    for n in sorted(fakt, key=lambda k: (k != 'лид', k)):
        b = byudzh.get(n)
        hvost = f'· бюджет {b:5} · {100 * fakt[n] / b - 100:+4.0f} %' if b else ''
        print(f'   раздел {n:>4}: {fakt[n]:6} {hvost}')
    print()

    if vsego > potolok:
        errs.append(f'[К5 потолок] проза {vsego} знаков при потолке {potolok} — '
                    f'превышение {100 * vsego / potolok - 100:.0f} %. Либо резать по '
                    f'«Порядку сокращения» из раскладки, либо поднимать потолок '
                    f'В РАСКЛАДКЕ с названной причиной — молча перерастать нельзя')

    for n, b in byudzh.items():
        if n not in fakt:
            continue
        izbytok = 100 * fakt[n] / b - 100
        if izbytok > 25:
            errs.append(f'[К5 бюджет] раздел {n}: {fakt[n]} знаков при бюджете {b} '
                        f'(+{izbytok:.0f} %) — раздел вышел из формы, а не подвинулся')
        elif izbytok > 0:
            warns.append(f'[К5 бюджет] раздел {n}: {fakt[n]} при бюджете {b} '
                         f'(+{izbytok:.0f} %) — допустимо, если общий потолок держится')


def main(path):
    src = Path(path).read_text(encoding='utf-8')
    meta, body = split_frontmatter(src)
    lead, rubrics = parse_body(body)
    items = [(rn, it) for rn, its in rubrics for it in its]
    # Лид проверяется теми же проходами, что и разделы: «оценки пошли навстречу
    # друг другу» стояло именно в нём и мимо гейта прошло дважды.
    items.insert(0, ('', {'title': 'ЛИД', 'blurb': lead, 'meta': {}}))

    errs, warns = [], []

    # К2 · подзаголовок выпуска
    sub = (meta.get('subtitle') or '').strip()
    if len(sub) > MAX_SUBTITLE:
        errs.append(f'[К2 подзаголовок] {len(sub)} симв. при потолке {MAX_SUBTITLE} → «{sub}»')
    for pat, why in BAD_SUBTITLE.items():
        if re.search(pat, sub, re.I):
            errs.append(f'[К2 подзаголовок] «{sub}» — {why}')

    # К1 · лид идёт от общего к частному: новость последним абзацем, не первым
    lp = [p for p in paras(lead) if p.strip()]
    if lp:
        first, last = lp[0], lp[-2] if len(lp) > 1 and 'шаг' in lp[-1].lower() else lp[-1]
        if re.search(r'\b(1[6-9]|20)\d\d\b', first) or re.search(r'\b(OpenAI|Google|DeepMind|Meta)\b', first):
            errs.append('[К1 лид] в первом абзаце лида год или организация — лид открывается '
                        'задачей, новость идёт последней (PROTOKOL-VYPUSKA.md К1)')
        if not re.search(r'\b(1[6-9]|20)\d\d\b', last):
            warns.append('[К1 лид] в последнем абзаце лида нет года — проверь, что новость '
                         'стоит в конце, а не в середине')

    stop = stop_words()

    def where(rn, it):
        return f'{rn} / {it["title"]}' if rn else it['title']

    for rn, it in items:
        loc = where(rn, it)

        # Г5 · каждая ссылка названа автором или площадкой — в подводке либо,
        # если название русское, в самом названии («Пост Левента Альпёге»).
        for ln in (it['meta'].get('links') or []):
            about, title = ln['about'], ln['title']
            # Русское название сами и придумываем, и оно законно несёт имя
            # («Пост Левента Альпёге»). Английское — оригинальный заголовок
            # работы, автора в нём не бывает, там смотрим только подводку.
            hunt = f'{title}. {about}' if re.search(r'[А-ЯЁ]', title) else about
            names = re.findall(r'(?<![.!?] )(?<!^)\b[А-ЯЁA-Z][а-яёa-z]{2,}', hunt)
            if not names:
                errs.append(f'[Г5 автор] {loc}: в подводке нет имени автора '
                            f'или площадки → «{about[:70]}…»')

        # Список меряется по пунктам: пункт — самостоятельная единица чтения,
        # и сумма пунктов порогом абзаца не считается.
        chunks = []
        for p in paras(it['blurb']):
            chunks.extend(bullets(p) or [p])

        for p in chunks:
            dm = display_math(p)

            # Г5 · выключная формула не короче порога.
            if dm is not None:
                if len(dm) < MIN_DISPLAY:
                    errs.append(f'[Г5 формула] {loc}: выключная формула короткая '
                                f'({len(dm)} симв.) → «{dm}». В строку или дописать')
                continue

            # Г5 · в телеграм-виде не осталось TeX.
            plain = render_inline_plain(p)
            leftover = re.findall(r'\\[a-zA-Z]+', plain)
            if leftover:
                errs.append(f'[Г5 TeX] {loc}: макрос не развёрнут для телеграма: '
                            f'{", ".join(sorted(set(leftover)))} — добавь в _TEX_WORDS')

            # К3 · рядом с математическим объектом — только глагол из белого списка.
            for m in re.finditer(rf'\b({MATH_NOUNS})\s+({VERB_TAIL})', p, re.I):
                verb = m.group(2)
                if re.search(r'(у|ю|ам|ах|ям|ях|ом|ой|ами|ями|е)$', m.group(1), re.I):
                    continue   # косвенный падеж: подлежащее не объект
                if not re.fullmatch(rf'({GOOD_VERBS})', verb, re.I):
                    errs.append(f'[К3 глагол] {loc}: «{m.group(0)}» — глагола нет в белом '
                                f'списке при математическом объекте. Действие делает человек '
                                f'(PROTOKOL-VYPUSKA.md К3)')

            # К4 · слова, которых мы не употребляем.
            for w, why in stop:
                if re.search(rf'\b{re.escape(w)}\w*', p, re.I):
                    errs.append(f'[К4 словарь] {loc}: «{w}» — {why}')

            # Г4 · глаголы намерения у математических объектов.
            for m in re.finditer(rf'\b({BAD_VERBS})\b', p, re.I):
                warns.append(f'[Г4 глагол] {loc}: «{m.group(1)}» — проверь, '
                             f'не приложен ли к абстракции')

            low = p.lower()
            for bad, why in BAD_PHRASES.items():
                if re.search(rf'\b{bad}\b', low):
                    warns.append(f'[стиль] {loc}: «{bad}» — {why}')

            if len(p) > MAX_PARA:
                warns.append(f'[объём] {loc}: абзац {len(p)} симв. — резать')

    # Носитель условия «OTCHET.md заполнен» из docs/fazy/tekst.md, гейт выхода, п. 4.
    # 🔴 Условие обещало «незаполненный отчёт красит гейт НЕЗАВИСИМО ОТ ТЕКСТА», и
    # носителя не имело ни в одном скрипте — проверено грепом по всем шести 16.08.
    # Тот же класс, что потолок объёма и граф опор: правило объявлено, рычага нет.
    # ⚠ Признак «выпуск ведётся по новому протоколу» — тот же, что у К5: блочные
    # маркеры. Выпуски 01–03 приняты без OTCHET.md, они старше протокола, и
    # краснеть на них нельзя. Проверено регрессией: без этой оговорки все три
    # принятых выпуска получали по ошибке Н2 на пустом месте.
    otchet = Path(path).parent / 'OTCHET.md'
    po_novomu_pr = re.search(r'^%%\s', body, re.M) is not None
    if not po_novomu_pr:
        pass                                   # старый выпуск: следа проверок у него нет
    elif not otchet.exists():
        errs.append('[Н2 отчёт] нет OTCHET.md — след проверок фазы `tekst` записывать некуда')
    else:
        to = otchet.read_text(encoding='utf-8')
        zaglushki = len(re.findall(r'\|\s*заполнить\s*\|', to))
        if zaglushki:
            errs.append(f'[Н2 отчёт] в OTCHET.md {zaglushki} строк(и) со словом-заглушкой '
                        f'«заполнить» — пустой след равен непроведённой проверке')

    # К5 · объём против потолка и бюджетов раскладки. Стоит ДО печати вердикта:
    # число объёма владелец должен видеть всегда, а не только когда оно красное.
    gejt_obyoma(Path(path).parent, body, errs, warns)

    # Г2 · термин определён там, где впервые появился: подсказка по обозначениям.
    order, seen = [], set()
    for rn, it in items:
        for p in paras(it['blurb']):
            for tok in re.findall(r'\\mathrm\{([A-Za-z]{1,4})\}|\b([A-Z]{2,3})_', p):
                name = tok[0] or tok[1]
                if name not in seen:
                    seen.add(name)
                    order.append((name, where(rn, it)))
    if order:
        print('Г2 · где обозначение впервые появляется (проверь, что там же и введено):')
        for name, loc in order:
            print(f'   {name:<6} ← {loc}')
        print()

    # Дисциплина гейта, взятая у graf_zavisimostej.py: скрипт сам печатает свои
    # слепые зоны. Иначе зелёный выход читается как «текст проверен», хотя
    # проверено только то, что снимается регулярками.
    print('НЕ проверяю (это Г1–Г5 руками, docs/pravila-vypuska.md §15):')
    for z in BLIND_ZONES:
        print(f'   · {z}')
    print()

    for w in warns:
        print('⚠ ' + w)
    for e in errs:
        print('✗ ' + e)

    if errs:
        print(f'\n✗ механический гейт красный: {len(errs)} ошибок, {len(warns)} подозрений')
        proverki.snyat(Path(path).parent, 'check_vypusk')
        return 1
    print(f'✓ механический гейт зелёный ({len(warns)} подозрений — глазами)\n')

    # 🔴 Носитель условия 1 гейта фазы `stil`: «каждое снятое срабатывание К3
    # объяснено следом, иначе список молча перестаёт работать».
    #
    # Механика барьера, а не напоминания: пока есть срабатывания белого списка
    # глаголов (К3) и словаря (К4), скрипт НЕ отмечает себя сам. Значит зелёным
    # он станет только после ручного `proverki.py mark … --sled "…"`, а `mark`
    # требует след не короче 20 знаков. Снять срабатывание молча больше нечем.
    #
    # ⚠ Правило померено ДО того, как стало барьером, — иначе оно покрасило бы
    # принятое. Замер 16.08 по трём принятым выпускам: срабатываний Г4/стиль
    # НОЛЬ в каждом. То есть у здорового текста их не бывает, и барьер срабатывает
    # ровно там, где автор действительно что-то снял. Сравни с правилом про
    # подводки ссылок: там замер показал обратное (больше половины принятых
    # подводок правило нарушают), и оно осталось измерением, а не гейтом.
    k3 = [w for w in warns if w.startswith(('[Г4 глагол]', '[стиль]'))]
    if k3:
        print(f'🔴 срабатываний белого списка К3/К4: {len(k3)} — сам себя НЕ отмечаю.')
        for w in k3:
            print(f'   · {w}')
        print('\n   Каждое снятое срабатывание объясняется в следе, иначе список молча\n'
              '   перестаёт работать. Снял их по существу — отметь проверку руками:\n'
              f'   python3 vypuski/proverki.py mark {Path(path).parent} check_vypusk \\\n'
              '       --sled "<по каждому: какое слово, к чему приложено, почему законно>"\n')
        proverki.snyat(Path(path).parent, 'check_vypusk')
        return proverki.gate(Path(path).parent, 'tekst')

    proverki.avtomark(Path(path).parent, 'check_vypusk',
                      f'механический гейт зелёный, {len(warns)} подозрений оставлено глазам')
    # Лист проверок фазы 2: скрипт зелёный не значит «выпуск проверен».
    return proverki.gate(Path(path).parent, 'tekst')



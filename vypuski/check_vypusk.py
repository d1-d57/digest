#!/usr/bin/env python3
"""Механические гейты выпуска — то, что можно проверить без чтения.

    python3 check_vypusk.py <дата>-vypusk-NN/vypusk.md

Проверяет Г5 из docs/pravila-vypuska.md §15 целиком и подсвечивает подозрительные
места для Г2 и Г4. Судить по-прежнему человеку: скрипт не редактор, он ловит
ровно те промахи, которые уже случались и стоили круга правок.

Чистый stdlib, сети не требует. Выход 0 — гейт зелёный, 1 — есть ошибки.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

sys.path.insert(0, str(Path(__file__).parent))
import proverki  # noqa: E402
from build_vypusk import (  # noqa: E402
    split_frontmatter, parse_body, paras, display_math, render_inline_plain, bullets,
)

# Глаголы, которые нельзя приложить к математическому объекту: у абстракции
# не бывает намерения и воли. Список растёт из реальных правок (pravila §7).
BAD_VERBS = r'требует|просит|хочет|говорит|пытается|стремится|прячет|диктует|заставляет|решает'
# Кальки и обороты, которые мы уже вычищали руками.
BAD_PHRASES = {
    'линия': 'калька в значении «направление работы» (russian-editor #37)',
    'в рамках': 'канцелярит',
    'на самом деле': 'нейросеточная подводка',
    'честно говоря': 'нейросеточная подводка',
    'это тот случай': 'нейросеточная подводка',
    'в каком-то смысле': 'нейросеточная подводка',
    # Абстракция не занимает позицию и не вступает в спор: против чего-то стоит
    # человек. Ловится не глаголом, а связкой — поэтому здесь, а не в BAD_VERBS.
    'стоял против': 'абстракция не может стоять против чего-то (pravila §7)',
    'стоит против': 'абстракция не может стоять против чего-то (pravila §7)',
    'идёт против': 'абстракция не может идти против чего-то (pravila §7)',
    'спорит с': 'абстракция не спорит (pravila §7)',
}
# --- К3 · БЕЛЫЙ список глаголов при математическом объекте -------------------
# ⚠ Белый список НЕ расширяют, чтобы погасить ложное срабатывание: 15.08 сюда дописали
# «держ\w+» ради «криптография держится на сложности» — и пропустили «границы держались
# десятилетиями», ровно ту ошибку, ради которой список заведён. Ложное срабатывание
# лечится переписыванием фразы, а не расширением списка.
# Чёрный список ловит только то, на чём мы уже обожглись: «оценки пошли навстречу
# друг другу» прошло мимо BAD_VERBS и дошло до владельца. Поэтому здесь обратный
# механизм — рядом с объектом допустим ТОЛЬКО глагол из списка, всё прочее красное.
MATH_NOUNS = (r'утвержден\w+|теорем\w+|гипотез\w+|лемм\w+|оценк\w+|границ\w+|задач\w+|'
              r'метод\w*|программ\w+|функци\w+|размерност\w+|плотност\w+|показател\w+|'
              r'множител\w+|упаковк\w+|решётк\w+|разрыв\w*|формул\w+')
GOOD_VERBS = (r'утвержда\w+|состои\w+|равн\w+|превосход\w+|меньше|больше|следу\w+|вытека\w+|'
              r'выполня\w+|верн\w+|неверн\w+|известн?\w*|неизвестн\w+|доказан\w*|опровергнут\w*|'
              r'получен\w*|построен\w*|сформулирован\w*|сводит\w+|совпада\w+|существу\w+|'
              r'проход\w+|прошл\w+|стоял\w+|стои\w+|доход\w+|дошл\w+|привод\w+|привел\w+|привёл|'
              r'улучшен\w*|сдвинул\w+|стремит\w+|имеет|имеют|стал\w*|станов\w+|закрыл\w*|определя\w+|обраща\w+|принима\w+|свел\w+|свёл|оказ\w+|дост\w+|'
              r'даёт|дают|дал|дала|дали|оста\w+|бы[лвo]\w*|'
              r'есть|нет|не|уже|тут|здесь|при|в|на|и|или|а|но')
VERB_TAIL = r'[а-яё]+(?:ет|ут|ют|ит|ат|ят|ли|ла|ло|л|лись|лась|ся)\b'

# К2 · подзаголовок выпуска
MAX_SUBTITLE = 50
BAD_SUBTITLE = {
    r'впервые за': 'все наши результаты про длинную историю — фраза не сообщает ничего (К2)',
    r'первое за': 'то же самое (К2)',
    r'\bзаявл\w+|по-видимому|предположительно': 'оговорка о статусе факта в заголовок не идёт (К2)',
    r'\bдвижени\w+': 'о математике говорят «продвижение», не «движение» (К2)',
}

MIN_DISPLAY = 24      # короче — формуле нечего делать на отдельной строке
MAX_PARA = 700        # длиннее — абзац не дочитывается

# Печатается на каждом прогоне. Список растёт из ошибок, которые скрипт
# пропустил: зелёный выход не должен читаться как «текст проверен».
BLIND_ZONES = [
    'направление импликации: «поэтому/значит/отсюда» — из чего что следует (Г2b)',
    'чего из утверждения НЕ следует — если читатель достроит сам, это пишется явно',
    'что именно доказано или сертифицировано — дословно по теореме, а не пересказом',
    'оборванное утверждение: назван объект, но не сказано, что про него утверждают',
    'термин чужой области без объяснения — и фальшивое объяснение через такие же слова',
    'неймдроппинг: цепочка имён, которыми читатель не может воспользоваться',
    'ссылка, дублирующая соседнюю по функции; абзац, на который ничто не опирается',
    'попсовая рамка, ярлык, регистр («пишем», «скажем так»)',
]


def stop_words():
    """К4 · слова, которых мы не употребляем. Дом списка — docs/slovar-stop.md."""
    f = Path(__file__).parent.parent / 'docs' / 'slovar-stop.md'
    if not f.exists():
        return []
    out = []
    for ln in f.read_text(encoding='utf-8').split('\n'):
        m = re.match(r'- `([^`]+)` · [^·]+ · (.+)', ln.strip())
        if m and '<' not in m.group(1):
            out.append((m.group(1).strip(), m.group(2).strip()))
    return out


def main(path):
    src = Path(path).read_text(encoding='utf-8')
    meta, body = split_frontmatter(src)
    lead, rubrics = parse_body(body)
    items = [(rn, it) for rn, its in rubrics for it in its]
    # Лид проверяется теми же проходами, что и разделы: «оценки пошли навстречу
    # друг другу» стояло именно в нём и мимо гейта прошло дважды.
    items.insert(0, ('', {'title': 'ЛИД', 'blurb': lead, 'meta': {}}))

    errs, warns = [], []

    # К2 · подзаголовок выпуска
    sub = (meta.get('subtitle') or '').strip()
    if len(sub) > MAX_SUBTITLE:
        errs.append(f'[К2 подзаголовок] {len(sub)} симв. при потолке {MAX_SUBTITLE} → «{sub}»')
    for pat, why in BAD_SUBTITLE.items():
        if re.search(pat, sub, re.I):
            errs.append(f'[К2 подзаголовок] «{sub}» — {why}')

    # К1 · лид идёт от общего к частному: новость последним абзацем, не первым
    lp = [p for p in paras(lead) if p.strip()]
    if lp:
        first, last = lp[0], lp[-2] if len(lp) > 1 and 'шаг' in lp[-1].lower() else lp[-1]
        if re.search(r'\b(1[6-9]|20)\d\d\b', first) or re.search(r'\b(OpenAI|Google|DeepMind|Meta)\b', first):
            errs.append('[К1 лид] в первом абзаце лида год или организация — лид открывается '
                        'задачей, новость идёт последней (PROTOKOL-VYPUSKA.md К1)')
        if not re.search(r'\b(1[6-9]|20)\d\d\b', last):
            warns.append('[К1 лид] в последнем абзаце лида нет года — проверь, что новость '
                         'стоит в конце, а не в середине')

    stop = stop_words()

    def where(rn, it):
        return f'{rn} / {it["title"]}' if rn else it['title']

    for rn, it in items:
        loc = where(rn, it)

        # Г5 · каждая ссылка названа автором или площадкой — в подводке либо,
        # если название русское, в самом названии («Пост Левента Альпёге»).
        for ln in (it['meta'].get('links') or []):
            about, title = ln['about'], ln['title']
            # Русское название сами и придумываем, и оно законно несёт имя
            # («Пост Левента Альпёге»). Английское — оригинальный заголовок
            # работы, автора в нём не бывает, там смотрим только подводку.
            hunt = f'{title}. {about}' if re.search(r'[А-ЯЁ]', title) else about
            names = re.findall(r'(?<![.!?] )(?<!^)\b[А-ЯЁA-Z][а-яёa-z]{2,}', hunt)
            if not names:
                errs.append(f'[Г5 автор] {loc}: в подводке нет имени автора '
                            f'или площадки → «{about[:70]}…»')

        # Список меряется по пунктам: пункт — самостоятельная единица чтения,
        # и сумма пунктов порогом абзаца не считается.
        chunks = []
        for p in paras(it['blurb']):
            chunks.extend(bullets(p) or [p])

        for p in chunks:
            dm = display_math(p)

            # Г5 · выключная формула не короче порога.
            if dm is not None:
                if len(dm) < MIN_DISPLAY:
                    errs.append(f'[Г5 формула] {loc}: выключная формула короткая '
                                f'({len(dm)} симв.) → «{dm}». В строку или дописать')
                continue

            # Г5 · в телеграм-виде не осталось TeX.
            plain = render_inline_plain(p)
            leftover = re.findall(r'\\[a-zA-Z]+', plain)
            if leftover:
                errs.append(f'[Г5 TeX] {loc}: макрос не развёрнут для телеграма: '
                            f'{", ".join(sorted(set(leftover)))} — добавь в _TEX_WORDS')

            # К3 · рядом с математическим объектом — только глагол из белого списка.
            for m in re.finditer(rf'\b({MATH_NOUNS})\s+({VERB_TAIL})', p, re.I):
                verb = m.group(2)
                if re.search(r'(у|ю|ам|ах|ям|ях|ом|ой|ами|ями|е)$', m.group(1), re.I):
                    continue   # косвенный падеж: подлежащее не объект
                if not re.fullmatch(rf'({GOOD_VERBS})', verb, re.I):
                    errs.append(f'[К3 глагол] {loc}: «{m.group(0)}» — глагола нет в белом '
                                f'списке при математическом объекте. Действие делает человек '
                                f'(PROTOKOL-VYPUSKA.md К3)')

            # К4 · слова, которых мы не употребляем.
            for w, why in stop:
                if re.search(rf'\b{re.escape(w)}\w*', p, re.I):
                    errs.append(f'[К4 словарь] {loc}: «{w}» — {why}')

            # Г4 · глаголы намерения у математических объектов.
            for m in re.finditer(rf'\b({BAD_VERBS})\b', p, re.I):
                warns.append(f'[Г4 глагол] {loc}: «{m.group(1)}» — проверь, '
                             f'не приложен ли к абстракции')

            low = p.lower()
            for bad, why in BAD_PHRASES.items():
                if re.search(rf'\b{bad}\b', low):
                    warns.append(f'[стиль] {loc}: «{bad}» — {why}')

            if len(p) > MAX_PARA:
                warns.append(f'[объём] {loc}: абзац {len(p)} симв. — резать')

    # Г2 · термин определён там, где впервые появился: подсказка по обозначениям.
    order, seen = [], set()
    for rn, it in items:
        for p in paras(it['blurb']):
            for tok in re.findall(r'\\mathrm\{([A-Za-z]{1,4})\}|\b([A-Z]{2,3})_', p):
                name = tok[0] or tok[1]
                if name not in seen:
                    seen.add(name)
                    order.append((name, where(rn, it)))
    if order:
        print('Г2 · где обозначение впервые появляется (проверь, что там же и введено):')
        for name, loc in order:
            print(f'   {name:<6} ← {loc}')
        print()

    # Дисциплина гейта, взятая у graf_zavisimostej.py: скрипт сам печатает свои
    # слепые зоны. Иначе зелёный выход читается как «текст проверен», хотя
    # проверено только то, что снимается регулярками.
    print('НЕ проверяю (это Г1–Г5 руками, docs/pravila-vypuska.md §15):')
    for z in BLIND_ZONES:
        print(f'   · {z}')
    print()

    for w in warns:
        print('⚠ ' + w)
    for e in errs:
        print('✗ ' + e)

    if errs:
        print(f'\n✗ механический гейт красный: {len(errs)} ошибок, {len(warns)} подозрений')
        return 1
    print(f'✓ механический гейт зелёный ({len(warns)} подозрений — глазами)\n')
    proverki.avtomark(Path(path).parent, 'check_vypusk',
                      f'механический гейт зелёный, {len(warns)} подозрений оставлено глазам')
    # Лист проверок фазы 2: скрипт зелёный не значит «выпуск проверен».
    return proverki.gate(Path(path).parent, 2)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))

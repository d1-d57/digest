#!/usr/bin/env python3
"""Механическая половина фазы `stil`. Три класса, которые ПАРСЯТСЯ.

    python3 check_stil.py <папка выпуска>

Требует spaCy и русскую модель:
    pip install spacy --break-system-packages && python3 -m spacy download ru_core_news_sm

🔴 ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ. Он НЕ ловит незаконную идиому — «граница ушла»,
«оценки пошли навстречу друг другу», «машинка дала ответ». Это установлено замером, а не
предположено:

  1. Переходность глагола не различает законное и незаконное. Проверено на парах из вердиктов
     владельца: «квантование МЕНЯЕТ алгебру» законно и переходно, «машинка ДАЛА ответ» незаконно и
     переходно; «граница ПРОХОДИТ» законна и непереходна, «граница УШЛА» незаконна и непереходна.
     Синтаксис границу не проводит.
  2. Различие лежит в СОЧЕТАЕМОСТИ пары (объект, глагол) — то есть в наборе, который, по словам
     владельца, «нельзя вывести из принципов, можно только сверить». Сверять надо по корпусу
     русской математической прозы либо по языковой модели.
  3. Ни то ни другое из песочницы недоступно: ru.wikipedia.org и ruscorpora.ru отдают 403, torch не
     устанавливается — на диске нет места. Дата проверки 2026-08-16.

Поэтому идиому здесь ловит только верификатор стиля с корпусом принятых выпусков на входе
(`docs/verifikatory/stil.md`), а зелёный этого скрипта НЕ означает «стиль проверен».
[ДОЛГ: docs/DOLGI.md#Д27]

ЧТО ЭТОТ СКРИПТ ДЕЛАЕТ — три класса, названные владельцем 16.08 и поддающиеся разбору.

КЛАСС А · лёгкий глагол + отглагольное существительное, сворачиваемое в один глагол.
  «попутно ДЕЛАЕТ УТВЕРЖДЕНИЕ о том, какая упаковка самая плотная» → утверждал
  «Gauss ЗАКРЫЛ ФОРМАЛИЗАЦИЮ за людьми» → формализовал
  Слова владельца: «эти два слова заменяются на одно… бессмысленное удлинение текста».
  Выдаётся ПОДОЗРЕНИЕМ, а не красным: замер по принятым выпускам 02 и 03 дал шесть срабатываний,
  и часть из них законна — «Название ДАЛ Вайс в 2000 году» владелец принял. Решает человек, и
  каждое снятое подозрение объясняется в следе проверки.

КЛАСС Б · самоповтор между полями замысла: `зачем` и `мысль` говорят одно и то же.
  Мера — доля общих лемм (существительные, глаголы, прилагательные). Порог 0.5 выведен замером:
  на выпусках 02 и 03 ноль срабатываний, на выпуске 04 — одно, блок 2.3, и оно настоящее.
  Это точный рычаг, и он краснеет.

КЛАСС В · вводные слова и хеджи общего русского: «вообще говоря», «на самом деле», «по сути»,
  «строго говоря», «заметим», «отметим», «легко видеть», «как известно».
  Замер 16.08 по выпускам 02, 03 и 04: **ноль вхождений на весь корпус**. То есть у нашего
  выпуска их не бывает — это факт корпуса, а не вкус. Краснеет.
  ⚠ Список закрытый и расширяется ТОЛЬКО замером по принятому выпуску: слово, встретившееся в
  выпуске со строкой приёмки, из списка выбрасывается, а не остаётся «на всякий случай».
"""
import glob
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import proverki  # noqa: E402

LEGKIE = {'делать', 'сделать', 'производить', 'произвести', 'осуществлять', 'осуществить',
          'проводить', 'провести', 'выполнять', 'выполнить', 'давать', 'дать', 'закрывать',
          'закрыть', 'вести', 'иметь', 'принимать', 'принять', 'оказывать', 'оказать',
          'подвергать', 'получать', 'получить'}
OTGLAG = re.compile(r'(ание|ение|ация|изация|овка|ировка)$')
STOP = {'быть', 'который', 'этот', 'тот', 'весь', 'свой', 'мочь', 'такой', 'один', 'два'}
PORQG_B = 0.5   # доля общих лемм, при которой `зачем` и `мысль` считаются одним и тем же
# Класс В. Ноль вхождений на выпуски 02–04: `python3 zamer_korpusa.py`, колонка «вводных».
VVODNYE = re.compile(
    r'\b(вообще говоря|на самом деле|по сути|строго говоря|разумеется|как известно|'
    r'нетрудно (видеть|заметить)|легко видеть|заметим|отметим|впрочем|пожалуй)\b', re.I)


def bloki(src):
    out = []
    for kus in re.split(r'^%% ', src, flags=re.M)[1:]:
        m = re.match(r'([\w.]+)\s*·\s*(\w+)', kus.split('\n', 1)[0])
        if not m:
            continue
        zamysel = kus.split('====')[0]
        proza = re.split(r'^# ', kus.split('====', 1)[1] if '====' in kus else '', flags=re.M)[0]
        pole = lambda k: (re.search(rf'^{k}:\s*(.+)$', zamysel, flags=re.M) or [None, ''])[1]
        out.append((m.group(1), m.group(2), pole('мысль'), pole('зачем'), proza))
    return out


def main(papka):
    try:
        import spacy
        nlp = spacy.load('ru_core_news_sm')
    except Exception as e:
        print(f'✗ нужен spaCy и модель ru_core_news_sm: {e}\n'
              f'  pip install spacy --break-system-packages\n'
              f'  python3 -m spacy download ru_core_news_sm')
        return 1

    d = Path(papka)
    if not d.is_dir():
        d = Path(__file__).parent / papka
    f = d / 'vypusk.md'
    if not f.exists():
        print(f'✗ нет {f}')
        return 1

    bl = bloki(f.read_text(encoding='utf-8'))
    podozr, bedy = [], []

    def lemmy(s):
        return {t.lemma_.lower() for t in nlp(s)
                if t.pos_ in ('NOUN', 'VERB', 'ADJ') and t.lemma_.lower() not in STOP}

    for nom, _st, mysl, zach, proza in bl:
        for t in nlp(proza):
            if t.pos_ == 'VERB' and t.lemma_.lower() in LEGKIE:
                for c in t.children:
                    if c.dep_ == 'obj' and c.pos_ == 'NOUN' and OTGLAG.search(c.lemma_.lower()):
                        podozr.append(f'{nom} · «{t.lemma_} {c.lemma_}» — сворачивается в один '
                                      f'глагол? · «{t.sent.text.strip()[:70]}»')
        for m in VVODNYE.finditer(proza):
            nachalo = max(0, m.start() - 40)
            bedy.append(f'{nom} · вводное «{m.group(0)}» — в принятых выпусках таких ноль'
                        f'\n      …{proza[nachalo:m.end() + 40].strip()}…')
        if mysl and zach:
            lm, lz = lemmy(mysl), lemmy(zach)
            if lm and lz:
                j = len(lm & lz) / len(lm | lz)
                if j >= PORQG_B:
                    bedy.append(f'{nom} · `зачем` и `мысль` совпадают на {j:.0%} — это одна мысль, '
                                f'сказанная дважды\n      зачем: {zach[:70]}\n      мысль: {mysl[:70]}')

    print(f'Блоков: {len(bl)}')
    print('⚠ ОХВАТ: проверены ТРИ класса — лёгкий глагол, самоповтор замысла, вводные. Идиома '
          '(«граница ушла») этим скриптом НЕ ловится и ловиться не может — см. докстринг.')
    print()
    for p in podozr:
        print('⚠ ' + p)
    if podozr:
        print(f'  подозрений класса А: {len(podozr)} — каждое снятое объясняется в следе проверки')
        print()
    for b in bedy:
        print('✗ ' + b)
    if bedy:
        print(f'\n✗ гейт стиля красный: находок {len(bedy)}')
        return 1
    print('✓ вводных нет, самоповторов замысла нет')
    proverki.avtomark(d, 'check_stil',
                      f'три класса по {len(bl)} блокам: подозрений А {len(podozr)}, самоповторов 0')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else '.'))
